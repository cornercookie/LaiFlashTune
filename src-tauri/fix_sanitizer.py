with open('src/open_with.rs', 'r') as f:
    lines = f.readlines()

# Fix 1: Add sanitize_chunk and finish methods to impl Sanitizer
new_lines = []
i = 0
while i < len(lines):
    line = lines[i]
    new_lines.append(line)
    # After '    }' that closes pub fn new(), add the missing methods before closing impl Sanitizer
    if i == 270:  # line 271 - '    }' closing pub fn new
        new_lines.append('\n')
        new_lines.append('    /// 處理一個字符串區塊，返回清洗後的結果。區塊之間狀態保留。\n')
        new_lines.append('    pub fn sanitize_chunk(&mut self, chunk: &str) -> String {\n')
        new_lines.append('        let mut out = String::with_capacity(chunk.len());\n')
        new_lines.append('        let mut chars = chunk.chars().peekable();\n')
        new_lines.append('        while let Some(c) = chars.next() {\n')
        new_lines.append('            if c.is_control() && c != \'\\t\' && c != \'\\n\' && c != \'\\r\' {\n')
        new_lines.append('                continue;\n')
        new_lines.append('            }\n')
        new_lines.append('            if self.in_query {\n')
        new_lines.append('                if c.is_whitespace() {\n')
        new_lines.append('                    self.in_query = false;\n')
        new_lines.append('                    self.in_url = false;\n')
        new_lines.append('                    out.push(c);\n')
        new_lines.append('                }\n')
        new_lines.append('                continue;\n')
        new_lines.append('            }\n')
        new_lines.append('            if self.in_non_url_query {\n')
        new_lines.append('                if c.is_whitespace() {\n')
        new_lines.append('                    self.in_non_url_query = false;\n')
        new_lines.append('                    out.push(c);\n')
        new_lines.append('                }\n')
        new_lines.append('                continue;\n')
        new_lines.append('            }\n')
        new_lines.append('            if !self.in_url && (c == \'h\' || c == \'H\') {\n')
        new_lines.append('                let mut potential = String::new();\n')
        new_lines.append('                potential.push(c);\n')
        new_lines.append('                let mut temp_chars = chars.clone();\n')
        new_lines.append('                let mut https_chars = temp_chars.clone();\n')
        new_lines.append('                let mut https_potential = potential.clone();\n')
        new_lines.append('                for expected in [\'t\', \'t\', \'p\', \'s\', \':\', \'/\', \'/\'] {\n')
        new_lines.append('                    if let Some(&next_c) = https_chars.peek() {\n')
        new_lines.append('                        if next_c.to_ascii_lowercase() == expected {\n')
        new_lines.append('                            https_potential.push(next_c);\n')
        new_lines.append('                            https_chars.next();\n')
        new_lines.append('                        } else {\n')
        new_lines.append('                            break;\n')
        new_lines.append('                        }\n')
        new_lines.append('                    } else {\n')
        new_lines.append('                        break;\n')
        new_lines.append('                    }\n')
        new_lines.append('                }\n')
        new_lines.append('                if https_potential.to_ascii_lowercase().starts_with("https://") {\n')
        new_lines.append('                    self.in_url = true;\n')
        new_lines.append('                    out.push_str(&https_potential);\n')
        new_lines.append('                    chars = https_chars;\n')
        new_lines.append('                    continue;\n')
        new_lines.append('                }\n')
        new_lines.append('                let mut http_chars = temp_chars.clone();\n')
        new_lines.append('                let mut http_potential = potential.clone();\n')
        new_lines.append('                for expected in [\'t\', \'t\', \'p\', \':\', \'/\', \'/\'] {\n')
        new_lines.append('                    if let Some(&next_c) = http_chars.peek() {\n')
        new_lines.append('                        if next_c.to_ascii_lowercase() == expected {\n')
        new_lines.append('                            http_potential.push(next_c);\n')
        new_lines.append('                            http_chars.next();\n')
        new_lines.append('                        } else {\n')
        new_lines.append('                            break;\n')
        new_lines.append('                        }\n')
        new_lines.append('                    } else {\n')
        new_lines.append('                        break;\n')
        new_lines.append('                    }\n')
        new_lines.append('                }\n')
        new_lines.append('                if http_potential.to_ascii_lowercase().starts_with("http://") {\n')
        new_lines.append('                    self.in_url = true;\n')
        new_lines.append('                    out.push_str(&http_potential);\n')
        new_lines.append('                    chars = http_chars;\n')
        new_lines.append('                    continue;\n')
        new_lines.append('                }\n')
        new_lines.append('                // SE3-006: file:// URL 支援\n')
        new_lines.append('                let mut file_chars = temp_chars.clone();\n')
        new_lines.append('                let mut file_potential = potential.clone();\n')
        new_lines.append('                for expected in [\'i\', \'l\', \'e\', \':\', \'/\', \'/\'] {\n')
        new_lines.append('                    if let Some(&next_c) = file_chars.peek() {\n')
        new_lines.append('                        if next_c.to_ascii_lowercase() == expected {\n')
        new_lines.append('                            file_potential.push(next_c);\n')
        new_lines.append('                            file_chars.next();\n')
        new_lines.append('                        } else {\n')
        new_lines.append('                            break;\n')
        new_lines.append('                        }\n')
        new_lines.append('                    } else {\n')
        new_lines.append('                        break;\n')
        new_lines.append('                    }\n')
        new_lines.append('                }\n')
        new_lines.append('                if file_potential.to_ascii_lowercase().starts_with("file://") {\n')
        new_lines.append('                    self.in_url = true;\n')
        new_lines.append('                    out.push_str(&file_potential);\n')
        new_lines.append('                    chars = file_chars;\n')
        new_lines.append('                    continue;\n')
        new_lines.append('                }\n')
        new_lines.append('            }\n')
        new_lines.append('            if self.in_url {\n')
        new_lines.append('                if c == \'?\' {\n')
        new_lines.append('                    self.in_query = true;\n')
        new_lines.append('                    continue;\n')
        new_lines.append('                }\n')
        new_lines.append('                if c == \'@\' {\n')
        new_lines.append('                    if let Some(pos) = out.rfind("://") {\n')
        new_lines.append('                        out.truncate(pos + 3);\n')
        new_lines.append('                        out.push_str("***@");\n')
        new_lines.append('                    } else {\n')
        new_lines.append('                        out.push(c);\n')
        new_lines.append('                    }\n')
        new_lines.append('                    continue;\n')
        new_lines.append('                }\n')
        new_lines.append('                if c.is_whitespace() || c.is_control() {\n')
        new_lines.append('                    self.in_url = false;\n')
        new_lines.append('                }\n')
        new_lines.append('            } else if c == \'?\' {\n')
        new_lines.append('                // 非 URL 環境下遇到 ?，進入查詢參數移除模式\n')
        new_lines.append('                self.in_non_url_query = true;\n')
        new_lines.append('                continue;\n')
        new_lines.append('            }\n')
        new_lines.append('            // 保留可列印字符、空格、tab、換行符（SE3-2）\n')
        new_lines.append('            if c.is_ascii_graphic() || c == \' \' || c == \'\\t\' || c == \'\\n\' || c == \'\\r\' {\n')
        new_lines.append('                out.push(c);\n')
        new_lines.append('            }\n')
        new_lines.append('        }\n')
        new_lines.append('        self.result.push_str(&out); out\n')
        new_lines.append('    }\n')
        new_lines.append('\n')
        new_lines.append('    pub fn finish(&mut self) -> String {\n')
        new_lines.append('        if self.result.len() > 1024 {\n')
        new_lines.append('            self.result.truncate(1024);\n')
        new_lines.append('        }\n')
        new_lines.append('        std::mem::take(&mut self.result)\n')
        new_lines.append('    }\n')
    i += 1

with open('src/open_with.rs', 'w') as f:
    f.writelines(new_lines)
