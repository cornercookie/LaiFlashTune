#!/usr/bin/env python3
# Append SymStream section

lines = []

lines.append("")
lines.append("pub struct SymStream {")
lines.append("    format: Box<dyn FormatReader>,")
lines.append("    decoder: Box<dyn SymDecoder>,")
lines.append("    track_id: u32,")
lines.append("    time_base: Option<TimeBase>,")
lines.append("    buf: Option<SampleBuffer<f32>>,")
lines.append("    buf_frames: u64,")
lines.append("    pos: usize,")
lines.append("    len: usize,")
lines.append("    skip_samples: usize,")
lines.append("    channels: u16,")
lines.append("    sample_rate: u32,")
lines.append("    duration_ms: Option<i64>,")
lines.append("    finished: bool,")
lines.append("    /// SE7：解碼錯誤跨封包累計")
lines.append("    decode_errors: usize,")
lines.append("}")
lines.append("")
lines.append("impl SymStream {")
lines.append("    /// 開檔並（可選）精準跳到 start_ms。回傳時已解出第一個封包，channels / sample_rate 可信。")
lines.append("    pub fn open(path: &Path, start_ms: i64) -> Result<Self, String> {")
lines.append("        let file = File::open(path).map_err(|e| format!(\"開啟檔案失敗: {e}\"))?;")
lines.append("        let mss = MediaSourceStream::new(Box::new(file), Default::default());")
lines.append("        let mut hint = Hint::new();")
lines.append("        if let Some(ext) = path.extension().and_then(|e| e.to_str()) {")
lines.append("            hint.with_extension(&ext.to_ascii_lowercase());")
lines.append("        }")
lines.append("        let format_opts = FormatOptions { enable_gapless: true, ..Default::default() };")
lines.append("        let probed = symphonia::default::get_probe()")
lines.append("            .format(&hint, mss, &format_opts, &MetadataOptions::default())")
lines.append("            .map_err(|e| format!(\"無法辨識格式: {e}\"))?;")
lines.append("        let format = probed.format;")
lines.append("        let track = format")
lines.append("            .tracks()")
lines.append("            .iter()")
lines.append("            .find(|t| t.codec_params.codec != CODEC_TYPE_NULL)")
lines.append("            .ok_or_else(|| \"檔案內沒有可解碼的音軌\".to_string())?;")
lines.append("        let track_id = track.id;")
lines.append("        let params = track.codec_params.clone();")
lines.append("        let decoder = symphonia::default::get_codecs()")
lines.append("            .make(&params, &DecoderOptions::default())")
lines.append("            .map_err(|e| format!(\"不支援的編碼: {e}\"))?;")
lines.append("        let duration_ms = params.time_base.zip(params.n_frames).map(|(tb, n)| {")
lines.append("            let t = tb.calc_time(n);")
lines.append("            (t.seconds as f64 * 1000.0 + t.frac * 1000.0) as i64")
lines.append("        });")
lines.append("        let mut s = Self {")
lines.append("            format,")
lines.append("            decoder,")
lines.append("            track_id,")
lines.append("            time_base: params.time_base,")
lines.append("            buf: None,")
lines.append("            buf_frames: 0,")
lines.append("            pos: 0,")
lines.append("            len: 0,")
lines.append("            skip_samples: 0,")
lines.append("            channels: params.channels.map(|c| c.count() as u16).unwrap_or(0),")
lines.append("            sample_rate: params.sample_rate.unwrap_or(0),")
lines.append("            duration_ms,")
lines.append("            finished: false,")
lines.append("            decode_errors: 0,")
lines.append("        };")
lines.append("        if start_ms > 0 {")
lines.append("            s.seek_ms(start_ms)?;")
lines.append("        }")
lines.append("        if !s.refill() && (s.channels == 0 || s.sample_rate == 0) {")
lines.append("            return Err(\"未解碼到任何音訊樣本\".into());")
lines.append("        }")
lines.append("        if s.channels == 0 || s.sample_rate == 0 {")
lines.append("            return Err(\"無法取得聲道或取樣率\".into());")
lines.append("        }")
lines.append("        Ok(s)")
lines.append("    }")
lines.append("")
lines.append("    pub fn duration_ms(&self) -> Option<i64> {")
lines.append("        self.duration_ms")
lines.append("    }")
lines.append("")
lines.append("    fn seek_ms(&mut self, ms: i64) -> Result<(), String> {")
lines.append("        let time = Time::from(ms.max(0) as f64 / 1000.0);")
lines.append("        let seeked = self")
lines.append("            .format")
lines.append("            .seek(SeekMode::Accurate, SeekTo::Time { time, track_id: Some(self.track_id) })")
lines.append("            .map_err(|e| format!(\"跳轉失敗: {e}\"))?;")
lines.append("        self.decoder.reset();")
lines.append("        self.pos = 0;")
lines.append("        self.len = 0;")
lines.append("        self.finished = false;")
lines.append("        // Accurate 模式落在 required_ts 之前的封包，多出來的樣本要丟掉。")
lines.append("        let delta = seeked.required_ts.saturating_sub(seeked.actual_ts);")
lines.append("        self.skip_samples = match (self.time_base, self.sample_rate, self.channels) {")
lines.append("            (Some(tb), rate, ch) if delta > 0 && rate > 0 && ch > 0 => {")
lines.append("                let t = tb.calc_time(delta);")
lines.append("                let secs = t.seconds as f64 + t.frac;")
lines.append("                (secs * rate as f64) as usize * ch as usize")
lines.append("            }")
lines.append("            _ => 0,")
lines.append("        };")
lines.append("        Ok(())")
lines.append("    }")
lines.append("")
lines.append("    /// 解下一個封包到 buf。回傳 false 代表檔案結束或無法繼續。")
lines.append("    fn refill(&mut self) -> bool {")
lines.append("        if self.finished {")
lines.append("            return false;")
lines.append("        }")
lines.append("        loop {")
lines.append("            let packet = match self.format.next_packet() {")
lines.append("                Ok(p) => p,")
lines.append("                Err(_) => {")
lines.append("                    self.finished = true;")
lines.append("                    return false;")
lines.append("                }")
lines.append("            };")
lines.append("            if packet.track_id() != self.track_id {")
lines.append("                continue;")
lines.append("            }")
lines.append("            // SE7：單封包上限")
lines.append("            if packet.buf().len() > MAX_PACKET_BYTES {")
lines.append("                self.finished = true;")
lines.append("                return false;")
lines.append("            }")
lines.append("            match self.decoder.decode(&packet) {")
lines.append("                Ok(decoded) => {")
lines.append("                    let spec = *decoded.spec();")
lines.append("                    if self.channels == 0 {")
lines.append("                        self.channels = spec.channels.count() as u16;")
lines.append("                    }")
lines.append("                    if self.sample_rate == 0 {")
lines.append("                        self.sample_rate = spec.rate;")
lines.append("                    }")
lines.append("                    let frames = decoded.capacity() as u64;")
lines.append("                    if self.buf.is_none() || frames > self.buf_frames {")
lines.append("                        self.buf = Some(SampleBuffer::<f32>::new(frames, spec));")
lines.append("                        self.buf_frames = frames;")
lines.append("                    }")
lines.append("                    let buf = self.buf.as_mut().unwrap();")
lines.append("                    buf.copy_interleaved_ref(decoded);")
lines.append("                    let len = buf.len();")
lines.append("                    if self.skip_samples >= len {")
lines.append("                        self.skip_samples -= len;")
lines.append("                        continue;")
lines.append("                    }")
lines.append("                    self.pos = self.skip_samples;")
lines.append("                    self.skip_samples = 0;")
lines.append("                    self.len = len;")
lines.append("                    if self.pos < self.len {")
lines.append("                        return true;")
lines.append("                    }")
lines.append("                }")
lines.append("                Err(SymError::DecodeError(_)) => {")
lines.append("                    self.decode_errors += 1;")
lines.append("                    if self.decode_errors > MAX_DECODE_ERRORS {")
lines.append("                        self.finished = true;")
lines.append("                        return false;")
lines.append("                    }")
lines.append("                }")
lines.append("                Err(_) => {")
lines.append("                    self.finished = true;")
lines.append("                    return false;")
lines.append("                }")
lines.append("            }")
lines.append("        }")
lines.append("    }")
lines.append("}")
lines.append("")
lines.append("impl Iterator for SymStream {")
lines.append("    type Item = f32;")
lines.append("    fn next(&mut self) -> Option<f32> {")
lines.append("        if self.pos >= self.len && !self.refill() {")
lines.append("            return None;")
lines.append("        }")
lines.append("        let s = self.buf.as_ref()?.samples()[self.pos];")
lines.append("        self.pos += 1;")
lines.append("        Some(s)")
lines.append("    }")
lines.append("}")
lines.append("")
lines.append("impl Source for SymStream {")
lines.append("    fn current_frame_len(&self) -> Option<usize> { None }")
lines.append("    fn channels(&self) -> u16 { self.channels }")
lines.append("    fn sample_rate(&self) -> u32 { self.sample_rate }")
lines.append("    fn total_duration(&self) -> Option<Duration> {")
lines.append("        self.duration_ms.map(|ms| Duration::from_millis(ms.max(0) as u64))")
lines.append("    }")
lines.append("}")

with open('src-tauri/src/audio_decode.rs', 'a') as f:
    f.write('\n'.join(lines))

print(f"Written {len(lines)} lines (SymStream)")