lines.append("const MAX_DECODE_ERRORS: usize = 10; // SE7：解碼錯誤跨封包累計，超過即終止")
lines.append("const MAX_PACKET_BYTES: usize = 256 * 1024; // SE7：Symphonia 單封包上限")
lines.append("const FFPROBE_MAX_BYTES: usize = 64 * 1024; // SE6：ffprobe stdout 上限")
lines.append("const FFPROBE_TIMEOUT: Duration = Duration::from_secs(10); // SE6：ffprobe 總逾時")
lines.append("")
lines.append("/// SE6：所有 ffprobe 呼叫點共用全域並行配額（同時最多 4 個進程）。")
lines.append("static FFPROBE_SLOTS_INIT: Once = Once::new();")
lines.append("static mut FFPROBE_SLOTS: Option[(Mutex<usize>, Condvar)> = None;")
lines.append("")
lines.append("/// 取得 ffprobe 配額槽位；無可用槽位時在 deadline 內等待，超時則拒絕整筆探測。")
lines.append("fn ffprobe_acquire_slot(deadline: Instant) -> Result<FfprobeSlot, String> {")
lines.append("    let sem = unsafe {")
lines.append("        FFPROBE_SLOTS_INIT.call_once(|| {")
lines.append("            FFPROBE_SLOTS = Some((Mutex::new(4usize), Condvar::new()));")
lines.append("        });")
lines.append("        FFPROBE_SLOTS.as_ref().expect(\"ffprobe quota initialised\")")
lines.append("    };")
lines.append("    let (lock, condvar) = sem;")
lines.append("    let mut slots = lock.lock().map_err(|e| format!(\"ffprobe 配額鎖定失敗: {e}\"))?;")
lines.append("    while *slots == 0 {")
lines.append("        let remaining = deadline.saturating_duration_since(Instant::now());")
lines.append("        if remaining.is_zero() {")
lines.append("            return Err(\"ffprobe 並行配額滿載（逾時）\".into());")
lines.append("        }")
lines.append("        let (next, _result) = condvar")
lines.append("            .wait_timeout(slots, remaining)")
lines.append("            .map_err(|e| format!(\"ffprobe 配額等待失敗: {e}\"))?;")
lines.append("        if *next > 0 {")
lines.append("            slots = next;")
lines.append("        } else {")
lines.append("            return Err(\"ffprobe 並行配額滿載（逾時）\".into());")
lines.append("        }")
lines.append("    }")
lines.append("    *slots -= 1;")
lines.append("    Ok(FfprobeSlot)")
lines.append("}")
lines.append("")
lines.append("/// ffprobe 配額槽位，Drop 時歸還槽位並喚醒等待者。")
lines.append("struct FfprobeSlot;")
lines.append("impl Drop for FfprobeSlot {")
lines.append("    fn drop(&mut self) {")
lines.append("        if let Some((lock, condvar)) = unsafe { FFPROBE_SLOTS.as_ref() } {")
lines.append("            let mut slots = lock.lock().unwrap();")
lines.append("            *slots += 1;")
lines.append("            condvar.notify_one();")
lines.append("        }")
lines.append("    }")
lines.append("}")
lines.append("")

# ffprobe_json
lines.append("/// 執行 ffprobe，並實作 64 KB / 10 秒上限（SE6，所有探測呼叫點皆應使用此）。")
lines.append("pub fn ffprobe_json(ffprobe_path: &Path, file_path: &str) -> Result<serde_json::Value, String> {")
lines.append("    use std::io::Read;")
lines.append("    let deadline = Instant::now() + FFPROBE_TIMEOUT;")
lines.append("    // SE6：全域四程序並行配額，超過則等待或拒絕")
lines.append("    let _slot = ffprobe_acquire_slot(deadline)?;")
lines.append("    let mut child = match Command::new(ffprobe_path)")
lines.append("        .args([\"-v\", \"error\", \"-print_format\", \"json\", \"-show_streams\", \"-show_format\", \"-protocol_whitelist\", \"file,pipe\", file_path])")
lines.append("        .stdout(Stdio::piped())")
lines.append("        .stderr(Stdio::piped())")
lines.append("        .spawn()")
lines.append("    {")
lines.append("        Ok(c) => c,")
lines.append("        Err(e) => return Err(format!(\"ffprobe 執行失敗: {e}\")),")
lines.append("    };")
lines.append("    let mut stdout = match child.stdout.take() {")
lines.append("        Some(s) => s,")
lines.append("        None => return Err(\"ffprobe 無 stdout\".into()),")
lines.append("    };")
lines.append("    let mut stderr = child.stderr.take();")
lines.append("    let mut out = Vec::new();")
lines.append("")
lines.append("    // SE6：使用獨立線程讀取 stdout，主線程用 recv_timeout 等待，避免阻塞讀取導致 deadline 無法生效")
lines.append("    let (tx, rx) = std::sync::mpsc::channel();")
lines.append("    let stdout_thread = std::thread::spawn(move || {")
lines.append("        let mut buf = [0u8; 8192];")
lines.append("        loop {")
lines.append("            match stdout.read(&mut buf) {")
lines.append("                Ok(0) => break,")
lines.append("                Ok(n) => {")
lines.append("                    if tx.send(buf[..n].to_vec()).is_err() { break; }")
lines.append("                }")
lines.append("                Err(_) => break,")
lines.append("            }")
lines.append("        }")
lines.append("        let _ = tx.send(Vec::new()); // 結束信號")
lines.append("    });")
lines.append("")
lines.append("    // 並行讀取並清洗 stderr，避免 ffprobe 因 stderr 緩衝區滿而阻塞")
lines.append("    let stderr_thread = std::thread::spawn(move || {")
lines.append("        use std::io::Read;")
lines.append("        let mut buf = vec![0u8; 4096];")
lines.append("        let mut sanitizer = crate::open_with::Sanitizer::new();")
lines.append("        if let Some(mut stderr) = stderr {")
lines.append("            loop {")
lines.append("                match stderr.read(&mut buf) {")
lines.append("                    Ok(0) => break,")
lines.append("                    Ok(n) => {")
lines.append("                        let chunk_text = String::from_utf8_lossy(&buf[..n]);")
lines.append("                        sanitizer.sanitize_chunk(&chunk_text);")
lines.append("                    }")
lines.append("                    Err(_) => break,")
lines.append("                }")
lines.append("            }")
lines.append("        }")
lines.append("        let cleaned = sanitizer.finish();")
lines.append("        if !cleaned.is_empty() {")
lines.append("            crate::open_with::log_line_raw(&cleaned);")
lines.append("        }")
lines.append("    });")
lines.append("")
lines.append("    'read: loop {")
lines.append("        if Instant::now() >= deadline {")
lines.append("            let _ = child.kill();")
lines.append("            return Err(\"ffprobe 逾時（10 秒）\".into());")
lines.append("        }")
lines.append("        match rx.recv_timeout(std::time::Duration::from_millis(100)) {")
lines.append("            Ok(chunk) if chunk.is_empty() => break 'read,")
lines.append("            Ok(chunk) => {")
lines.append("                let remain = FFPROBE_MAX_BYTES.saturating_sub(out.len());")
lines.append("                if remain == 0 {")
lines.append("                    let _ = child.kill();")
lines.append("                    return Err(\"ffprobe 輸出超過 64 KB\".into());")
lines.append("                }")
lines.append("                let take = chunk.len().min(remain);")
lines.append("                out.extend_from_slice(&chunk[..take]);")
lines.append("                if take < chunk.len() {")
lines.append("                    let _ = child.kill();")
lines.append("                    return Err(\"ffprobe 輸出超過 64 KB\".into());")
lines.append("                }")
lines.append("            }")
lines.append("            Err(std::sync::mpsc::RecvTimeoutError::Timeout) => continue 'read,")
lines.append("            Err(_) => break 'read,")
lines.append("        }")
lines.append("    }")
lines.append("")
lines.append("    let _ = stdout_thread.join();")
lines.append("    let _ = stderr_thread.join();")
lines.append("    let _ = child.wait();")
lines.append("    let text = String::from_utf8_lossy(&out);")
lines.append("    serde_json::from_str(&text).map_err(|e| format!(\"ffprobe JSON 解析失敗: {e}\"))")
lines.append("}")
lines.append("")

