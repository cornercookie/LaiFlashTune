lines.append("            let mut chunk = Vec::with_capacity(CHUNK_SAMPLES * 4);")
lines.append("            let mut buf = [0u8; 8192];")
lines.append("            ")
lines.append("            loop {")
lines.append("                if cancel_stdout.is_cancelled() {")
lines.append("                    break;")
lines.append("                }")
lines.append("                ")
