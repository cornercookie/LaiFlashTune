lines.append("        let file_path = self.file_path.clone();")
lines.append("        let channels = self.channels as usize;")
lines.append("        let sample_rate = self.sample_rate.max(1);")
lines.append("        let cancel = self.cancel.clone();")
lines.append("        let (tx, rx) = crossbeam_channel::bounded(128);")
