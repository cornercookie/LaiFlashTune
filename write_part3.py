lines.append("                            Err(e) => {")
lines.append("                                eprintln!(\"ffmpeg spawn failed: {e}\");")
lines.append("                                return;")
lines.append("                            }")
lines.append("                        };")
lines.append("            ")
lines.append("                        // 先取出 stdout 和 stderr，再移動 child")
