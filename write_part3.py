lines.append("                            Some(out) => out,")
lines.append("                            None => return,")
lines.append("                        };")
lines.append("            ")
lines.append("                        let mut stderr = child.stderr.take();")
lines.append("            ")
lines.append("                        cancel_stdout.set_child(child);")
