lines.append("                        // stderr 讀取執行緒：使用持久化 Sanitizer 跨區塊保留 in_url/in_query 狀態")
lines.append("                        let stderr_thread = thread::spawn(move || {")
lines.append("                            use std::io::Read;")
lines.append("                            let mut buf = vec![0u8; 4096];")
lines.append("                            let mut sanitizer = crate::open_with::Sanitizer::new();")
lines.append("                            if let Some(mut stderr) = stderr {")
lines.append("                                loop {")
lines.append("                                    if cancel_stderr.is_cancelled() {")
lines.append("                                        break;")
lines.append("                                    }")
lines.append("                                    match stderr.read(&mut buf) {")
lines.append("                                        Ok(0) => break,")
lines.append("                                        Ok(n) => {")
lines.append("                                            let chunk_text = String::from_utf8_lossy(&buf[..n]);")
lines.append("                                            sanitizer.sanitize_chunk(&chunk_text);")
lines.append("                                        }")
lines.append("                                        Err(_) => break,")
lines.append("                                    }")
lines.append("                                }")
lines.append("                            }")
lines.append("                            // 確保所有結束路徑（cancel、EOF、Err）均呼叫 finish()")
lines.append("                            let cleaned = sanitizer.finish();")
lines.append("                            if !cleaned.is_empty() {")
lines.append("                                crate::open_with::log_line_raw(&cleaned);")
