lines.append("                .stderr(Stdio::piped())")
lines.append("                .spawn() else {")
lines.append("                let _ = tx.send(Vec::new());")
lines.append("                return;")
lines.append("            };")
lines.append("            let mut stdout = match child.stdout.take() {")
lines.append("                Some(o) => o,")
lines.append("                None => { let _ = tx.send(Vec::new()); return; },")
lines.append("            };")
lines.append("")
lines.append("            // stderr 讀取執行緒：使用持久化 Sanitizer 跨區塊保留 in_url/in_query 狀態")
